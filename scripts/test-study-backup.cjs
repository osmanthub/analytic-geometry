const assert = require('node:assert/strict');
const backup = require('../docs/study-backup.js');
const empty = {course:'geometry-lab',schema:1,topics:[],records:{}};
const sample = {...empty,topics:['v-1'],records:{q1:{notes:['条件','计算'],reflection:'核对',viewed:true}}};
const current = {...empty,topics:['v-2'],records:{q1:{notes:['本机条件',''],reflection:'',viewed:false}}};
assert.throws(()=>backup.validate({schema:2}));
assert.throws(()=>backup.validate({...empty,records:JSON.parse('{"__proto__":{"notes":[],"reflection":"","viewed":false}}')}));
assert.throws(()=>backup.validate({...empty,records:{q1:{notes:[3],reflection:'',viewed:false}}}));
const result = backup.merge(current,sample);
assert.equal(result.conflicts,1);assert.deepEqual(result.data.topics,['v-2','v-1']);
assert.deepEqual(result.data.records.q1,{notes:['本机条件','计算'],reflection:'核对',viewed:true});
const data = new Map(); let failOnce = false;
const storage = {getItem:key=>data.get(key)??null,setItem:(key,val)=>{if(failOnce&&key==='geometry-worked-v1'){failOnce=false;throw Error('quota');}data.set(key,val);},removeItem:key=>data.delete(key)};
backup.restore(storage,sample);assert.deepEqual(backup.read(storage),backup.validate(sample));
const before = [...data];failOnce=true;
assert.throws(()=>backup.restore(storage,current),/保留恢复前/);assert.deepEqual([...data],before);
assert.equal(Object.prototype.polluted,undefined);
storage.setItem('geometry-worked-v1',JSON.stringify({q1:{notes:[null,'stage two'],reflection:'',viewed:false}}));
assert.deepEqual(backup.read(storage).records.q1.notes,['','stage two']);
console.log('PASS: round trip, merge without overwriting existing text, validation, prototype keys, storage rollback.');
